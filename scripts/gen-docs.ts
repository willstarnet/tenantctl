/**
 * Generate docs/COMMANDS.md and docs/PERMISSIONS.md from the command registry, so the reference never drifts
 * from the code. Run with `bun run docs`.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { kebab } from '../src/core/args.ts';
import type { AnyCommand } from '../src/core/types.ts';
import { COMMANDS, commandId, DOMAINS, usage } from '../src/registry.ts';

const root = join(import.meta.dir, '..');
const LOCAL_AREAS: Record<string, true> = { auth: true, config: true, tools: true, permissions: true, graph: true };
const escape = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function commandSection(command: AnyCommand): string {
  const lines = [
    `### \`tenantctl ${commandId(command)}\``,
    '',
    `${command.summary}${command.risk === 'read' ? '' : ` **[${command.risk}]**`}`,
    '',
  ];
  if (command.description) lines.push(command.description, '');
  lines.push('```', usage(command), '```', '');
  if (command.args.length) {
    lines.push('| Argument | Type | Description |', '|---|---|---|');
    for (const arg of command.args) {
      const flag = arg.positional ? `\`<${kebab(arg.name)}>\` / \`--${kebab(arg.name)}\`` : `\`--${kebab(arg.name)}\``;
      const notes = [
        arg.required ? 'required' : '',
        arg.choices ? `one of \`${arg.choices.join('`, `')}\`` : '',
        arg.default !== undefined ? `default \`${String(arg.default)}\`` : '',
      ].filter(Boolean);
      lines.push(
        `| ${flag} | ${arg.type} | ${escape(arg.description)}${notes.length ? ` (${notes.join('; ')})` : ''} |`,
      );
    }
    lines.push('');
  }
  if (command.examples?.length) lines.push('Examples:', '', '```sh', ...command.examples, '```', '');
  const { delegated, application, roles, exchange, defender } = command.permissions;
  const perms = [
    delegated?.length ? `delegated \`${delegated.join('`, `')}\`` : '',
    application?.length ? `application \`${application.join('`, `')}\`` : '',
    exchange ? 'Exchange Online PowerShell (`Exchange.Manage` / `Exchange.ManageAsApp`)' : '',
    defender?.length ? `Defender for Endpoint \`${defender.join('`, `')}\`` : '',
    roles?.length ? `role ${roles.join(' or ')}` : '',
  ].filter(Boolean);
  if (perms.length) lines.push(`Permissions: ${perms.join('; ')}`, '');
  return lines.join('\n');
}

/** GitHub's heading anchor for a command section, e.g. "tenantctl intune devices get" -> "tenantctl-intune-devices-get". */
const anchor = (command: AnyCommand) =>
  `tenantctl ${commandId(command)}`
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, '')
    .replace(/ /g, '-');

const index = DOMAINS.flatMap((domain) => {
  const list = COMMANDS.filter((c) => c.domain === domain.name);
  if (!list.length) return [];
  return [
    `**${domain.name}**: ${domain.summary}`,
    '',
    '| Command | What it does | Risk |',
    '|---|---|---|',
    ...list.map((c) => `| [\`${commandId(c)}\`](#${anchor(c)}) | ${escape(c.summary)} | ${c.risk} |`),
    '',
  ];
});

const commandsMd = [
  '# Command reference',
  '',
  '<!-- Generated by `bun run docs` from src/registry.ts. Do not edit by hand. -->',
  '',
  `Every \`tenantctl\` command (${COMMANDS.length}), grouped by area. \`tenantctl <area> <command> --help\` shows the same detail, and \`tenantctl tools --json\` gives it as JSON Schema for agents.`,
  '',
  'Risk: **read** changes nothing; **write** needs writes enabled; **destructive** also needs a person to approve the preview (OS dialog or terminal prompt; a `--confirm` token in `token` mode).',
  '',
  '## Index',
  '',
  ...index,
  ...DOMAINS.flatMap((domain) => {
    const list = COMMANDS.filter((c) => c.domain === domain.name);
    if (!list.length) return [];
    return [`## ${domain.name}`, '', domain.summary, '', ...list.map(commandSection)];
  }),
].join('\n');

function permissionTable(kind: 'delegated' | 'application', includeWrites: boolean): string[] {
  const byPermission = new Map<string, string[]>();
  for (const command of COMMANDS) {
    if (LOCAL_AREAS[command.domain] || (!includeWrites && command.risk !== 'read')) continue;
    if (includeWrites && command.risk === 'read') continue;
    for (const permission of command.permissions[kind] ?? []) {
      byPermission.set(permission, [...(byPermission.get(permission) ?? []), commandId(command)]);
    }
  }
  return [
    '| Permission | Used by |',
    '|---|---|',
    ...[...byPermission.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([permission, ids]) => `| \`${permission}\` | ${ids.map((id) => `\`${id}\``).join(', ')} |`),
  ];
}

const permissionsMd = [
  '# Graph permissions',
  '',
  '<!-- Generated by `bun run docs` from src/registry.ts. Do not edit by hand. -->',
  '',
  'Least-privileged Microsoft Graph permissions per command. `tenantctl permissions --mode application` prints the',
  'same union for an app registration; `tenantctl auth login` requests the delegated set automatically.',
  '',
  '## Application permissions (app-only profiles)',
  '',
  '### Read-only commands',
  '',
  ...permissionTable('application', false),
  '',
  '### Additional for write commands',
  '',
  ...permissionTable('application', true),
  '',
  '## Delegated permissions (signed-in admin)',
  '',
  'Delegated calls also need the signed-in user to hold a suitable admin role; see each command in COMMANDS.md.',
  '',
  '### Read-only commands',
  '',
  ...permissionTable('delegated', false),
  '',
  '### Additional for write commands',
  '',
  ...permissionTable('delegated', true),
  '',
].join('\n');

writeFileSync(join(root, 'docs', 'COMMANDS.md'), `${commandsMd}\n`);
writeFileSync(join(root, 'docs', 'PERMISSIONS.md'), permissionsMd);
console.log(`docs/COMMANDS.md (${COMMANDS.length} commands), docs/PERMISSIONS.md`);
